// =============================================================================
//  FilterChain.h
//
//  Project : IEM-500 Filter Correction Suite
//  Purpose : Corrected top-level signal chain.
//
//  Description
//  -----------
//  Corrected chain for the IEM-500 inductor EQ emulation.
//
//  Order of operations:
//
//      in --> HPF (ALWAYS ACTIVE) --> [ bypass ? pass : EQ bands ] -->
//             --> coupling transformer (ALWAYS IN CIRCUIT, OVERSAMPLED) --> out
//
//  Two defects are corrected relative to conventional plugin designs:
//
//    1. The high-pass section is instantiated outside the bypass conditional.
//       Toggling `setBypass()` therefore does not remove the HPF from the
//       signal path, and does not reset its state. A bypass transition
//       produces no click from the high-pass stage.
//
//    2. The coupling transformer is a nonlinear magnetic stage. It is driven
//       at the oversampled rate through `Oversampler`, never at the host rate.
//       This prevents harmonics generated by the hysteresis model from
//       aliasing back into the audible band.
//
//  Thread safety
//  -------------
//  Not thread-safe. `prepare`, `reset`, `setBypass`, and
//  `setOversamplingFactor` must be called outside the audio callback or under
//  a lock. `process` is real-time safe and performs no allocation.
// =============================================================================

#pragma once

#include <cstddef>

#include "HpfSection.h"
#include "LpfSection.h"
#include "JilesAtherton.h"
#include "Oversampler.h"

namespace iem500 {

// -----------------------------------------------------------------------------
//  FilterChain
// -----------------------------------------------------------------------------

class FilterChain {
public:
    static constexpr int kDefaultOversampling = 8;

    FilterChain() noexcept = default;
    ~FilterChain() noexcept = default;

    FilterChain(const FilterChain&)            = delete;
    FilterChain& operator=(const FilterChain&) = delete;
    FilterChain(FilterChain&&) noexcept        = default;
    FilterChain& operator=(FilterChain&&) noexcept = default;

    // -------------------------------------------------------------------------
    //  Lifecycle
    // -------------------------------------------------------------------------

    // Prepares all stages for the given sample rate. The transformer model is
    // readied at the oversampled rate. Resets every stage.
    void prepare(double sampleRate, std::size_t blockSize = 512) noexcept;

    // Clears all internal state without altering configuration.
    void reset() noexcept;

    // -------------------------------------------------------------------------
    //  Bypass
    //
    //  Disengages the EQ bands only. The high-pass section and the coupling
    //  transformer remain in circuit by design.
    // -------------------------------------------------------------------------

    void setBypass(bool bypass) noexcept { bypass_ = bypass; }
    bool bypass() const noexcept { return bypass_; }

    // -------------------------------------------------------------------------
    //  Audio
    // -------------------------------------------------------------------------

    // Processes one sample through the full chain.
    double process(double x) noexcept;

    // -------------------------------------------------------------------------
    //  Oversampling
    // -------------------------------------------------------------------------

    void setOversamplingFactor(int factor);
    int  oversamplingFactor() const noexcept { return oversampler_.factor(); }

    // -------------------------------------------------------------------------
    //  Introspection
    // -------------------------------------------------------------------------

    double latencySamples() const noexcept { return latency_; }
    double sampleRate() const noexcept { return sampleRate_; }

    // -------------------------------------------------------------------------
    //  Sub-module access
    // -------------------------------------------------------------------------

    HpfSection&    hpf()         noexcept { return hpf_; }
    LpfSection&    lpf()         noexcept { return lpf_; }
    JilesAtherton& transformer() noexcept { return transformer_; }
    Oversampler&   oversampler() noexcept { return oversampler_; }

private:
    void updateLatency() noexcept;

    HpfSection    hpf_{};
    LpfSection    lpf_{};
    JilesAtherton transformer_{};
    Oversampler   oversampler_{kDefaultOversampling};

    bool   bypass_{false};
    double sampleRate_{48000.0};
    double latency_{0.0};
};

} // namespace iem500
